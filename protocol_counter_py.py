from scapy.all import *
from collections import Counter

packets = rdpcap("day2_capture.pcapng")

ips = []

for pkt in packets:
    if IP in pkt:
        ips.append(pkt[IP].src)
        ips.append(pkt[IP].dst)

counter = Counter(ips)

print(counter.most_common(10))

