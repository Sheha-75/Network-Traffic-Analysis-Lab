packets = rdpcap("day2_capture.pcapng")

protocol_counter = Counter()

for pkt in packets:

    if pkt.haslayer("TCP"):
        protocol_counter["TCP"] += 1

    elif pkt.haslayer("UDP"):
        protocol_counter["UDP"] += 1

    elif pkt.haslayer("ICMP"):
        protocol_counter["ICMP"] += 1

